const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, ko };

/** BCP 47 tags for Intl date and number formatting. */
export const INTL_LOCALE: Record<Locale, string> = { en: "en-US", ko: "ko-KR" };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const table = MESSAGES[locale] ?? en;
  return (key, vars) => table[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`));
}
